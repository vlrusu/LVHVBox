#!/usr/bin/env python3
"""Generate C/Python protocol definitions. No third-party build dependencies."""
import argparse
import hashlib
import json
from pathlib import Path
import struct


def outputs(root):
    raw = (root / 'protocol/lvhv.json').read_bytes()
    schema = json.loads(raw)
    assert schema['byte_order'] in ('little', 'big')
    endian = '<' if schema['byte_order'] == 'little' else '>'
    assert schema['count_format'] == 'I' and schema['count_bytes'] == 4
    assert 1 <= len(schema['magic'].encode('ascii')) <= 255
    assert 1 <= schema['max_blocks'] <= 1024 * 1024
    assert 9 + len(schema['magic']) <= schema['max_message_bytes'] <= 64 * 1024 * 1024
    assert 0 < schema['frame_timeout_ms'] <= 60000
    for key, item in schema['types'].items():
        assert len(key) == 1 and key.isascii()
        assert struct.calcsize(endian + item['format']) == item['bytes']
    assert all(item['type'] in schema['types'] and item['count'] == 1 for item in schema['request'])
    assert {i['name'] for i in schema['request']} == {'command', 'subsystem', 'channel', 'numeric'}
    digest = hashlib.sha256(raw).hexdigest()
    py = '# Generated by protocol/generate.py from protocol/lvhv.json; do not edit.\n'
    definitions = dict(DEFINITION_SHA256=digest, ENDIAN=endian, MAGIC=schema['magic'].encode(),
        COUNT_FORMAT=endian + schema['count_format'], COUNT_BYTES=schema['count_bytes'],
        TYPES=schema['types'], REQUEST=tuple((i['type'], i['count']) for i in schema['request']),
        REQUEST_FIELDS=tuple((i['name'], i['type'], i['count']) for i in schema['request']),
        MAX_BLOCKS=schema['max_blocks'], MAX_MESSAGE_BYTES=schema['max_message_bytes'],
        FRAME_TIMEOUT_MS=schema['frame_timeout_ms'])
    for key, value in definitions.items():
        py += f'{key} = {value!r}\n'
    h = ['/* Generated by protocol/generate.py; do not edit. */',
         '#ifndef LVHV_PROTOCOL_GENERATED_H', '#define LVHV_PROTOCOL_GENERATED_H',
         '#include <stdint.h>', f'#define LVHV_DEFINITION_SHA256 "{digest}"',
         f'#define LVHV_MAGIC "{schema["magic"]}"',
         f'#define LVHV_MAGIC_BYTES {len(schema["magic"])}u',
         f'#define LVHV_LITTLE_ENDIAN {int(schema["byte_order"] == "little")}',
         f'#define LVHV_COUNT_BYTES {schema["count_bytes"]}u',
         '#define LVHV_BLOCK_HEADER_BYTES (1u + LVHV_COUNT_BYTES)',
         f'#define LVHV_MAX_BLOCKS {schema["max_blocks"]}u',
         f'#define LVHV_MAX_MESSAGE_BYTES {schema["max_message_bytes"]}u',
         '#ifndef LVHV_FRAME_TIMEOUT_MS',
         f'#define LVHV_FRAME_TIMEOUT_MS {schema["frame_timeout_ms"]}', '#endif',
         f'#define LVHV_REQUEST_FIELDS {len(schema["request"])}u',
         'static const char LVHV_REQUEST_TYPES[] = {' + ', '.join(repr(i['type']) for i in schema['request']) + '};',
         'static const uint32_t LVHV_REQUEST_COUNTS[] = {' + ', '.join(str(i['count']) + 'u' for i in schema['request']) + '};',
         'static inline unsigned int lvhv_type_size(char type) {', '  switch (type) {']
    h += [f"    case {key!r}: return {item['bytes']}u;" for key, item in schema['types'].items()]
    h += ['    default: return 0;', '  }', '}']
    h += [f'#define LVHV_REQUEST_{item["name"].upper()} {i + 1}u' for i, item in enumerate(schema['request'])]
    h += ['#endif', '']
    return {'Client/lvhv_protocol_generated.py': py,
            'lvhv-server/messaging/Protocol.h': '\n'.join(h)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    stale = []
    for name, content in outputs(args.root).items():
        path = args.root / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, 'Stale protocol definitions: ' + ', '.join(stale) + '; run protocol/generate.py\n')


if __name__ == '__main__':
    main()
